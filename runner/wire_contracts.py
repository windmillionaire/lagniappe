"""Generate browser polling types and the standalone MCP adapter's API schemas."""

import argparse
from collections.abc import Mapping
import json
import os
from pathlib import Path
from tempfile import TemporaryDirectory
from types import UnionType
from typing import (
    Any,
    Literal,
    NotRequired,
    Union,
    TypeAliasType,
    cast,
    get_args,
    get_origin,
    get_type_hints,
    is_typeddict,
)


ROOT = Path(__file__).resolve().parents[1]
POLL_OUTPUT = Path("src/script/generated/poll.ts")
MCP_OUTPUT = Path("mcp/src/lagniappe_mcp/wire_schemas.json")


def _ts_type(annotation: Any) -> str:
    primitive = {
        str: "string",
        bool: "boolean",
        int: "number",
        type(None): "null",
        object: "unknown",
    }
    if annotation in primitive:
        return primitive[annotation]
    if isinstance(annotation, TypeAliasType):
        return annotation.__name__
    origin, args = get_origin(annotation), get_args(annotation)
    if origin is Literal:
        return " | ".join(json.dumps(item) for item in args)
    if origin is NotRequired:
        return _ts_type(args[0])
    if origin in (Union, UnionType):
        return " | ".join(_ts_type(item) for item in args)
    if origin in (list, tuple):
        return f"Array<{_ts_type(args[0])}>"
    if origin is dict and args[0] is str:
        return f"Record<string, {_ts_type(args[1])}>"
    if is_typeddict(annotation):
        return annotation.__name__
    raise ValueError(f"Unsupported poll wire annotation: {annotation!r}")


def _interface(model: type) -> str:
    lines = [f"export interface {model.__name__} {{"]
    for key, hint in get_type_hints(model, include_extras=True).items():
        optional = "?" if get_origin(hint) is NotRequired else ""
        lines.append(f"\t{key}{optional}: {_ts_type(hint)};")
    return "\n".join([*lines, "}"])


def render_poll() -> str:
    from lagniappe.core.tools.cache import documents
    from lagniappe.core.tools.polling import contract as poll
    from lagniappe.core.properties.deferred_job_lifecycle import JobStatus

    constants = {
        "POLL_PROTOCOL_VERSION": poll.POLL_PROTOCOL_VERSION,
        "MAX_SUBSCRIPTIONS_PER_REQUEST": poll.MAX_POLL_SUBSCRIPTIONS,
        "MAX_TYPE_LENGTH": poll.MAX_POLL_TYPE_LENGTH,
        "MAX_CHANNEL_LENGTH": poll.MAX_POLL_CHANNEL_LENGTH,
        "MAX_KEY_LENGTH": poll.MAX_POLL_KEY_LENGTH,
        "MAX_IDENTIFIER_LENGTH": poll.MAX_POLL_IDENTIFIER_LENGTH,
        "MAX_CLIENT_ID_LENGTH": poll.MAX_POLL_CLIENT_ID_LENGTH,
        "MAX_CURSOR_LENGTH": poll.MAX_POLL_CURSOR_LENGTH,
        "MAX_STATE_TOKEN_LENGTH": poll.MAX_POLL_STATE_TOKEN_LENGTH,
        "MAX_REVISION": poll.MAX_POLL_REVISION,
        "CHANNELS": sorted(poll.POLL_CHANNELS),
        "DESCRIPTOR_FIELDS": poll.DESCRIPTOR_FIELDS,
        "NOTIFICATION_FIELDS": poll.NOTIFICATION_FIELDS,
        "REQUEST_FIELDS": poll.REQUEST_FIELDS,
        "OPTIONAL_REQUEST_FIELDS": poll.OPTIONAL_REQUEST_FIELDS,
        "RESULT_FIELDS": poll.RESULT_FIELDS,
        "RESULT_MEMBERS": poll.RESULT_MEMBERS,
    }
    lines = ["// Generated by runner.wire_contracts from the Python polling contract."]
    for name, value in constants.items():
        suffix = " as const" if not isinstance(value, int) else ""
        lines.append(f"export const {name} = {json.dumps(value)}{suffix};")

    models = (
        documents.DocumentAuthor,
        documents.DocumentReader,
        documents.PresentReader,
        documents.DocumentDelta,
        documents.DocumentPoll,
        JobStatus,
        poll.EntityPayload,
        poll.RefreshPayload,
        poll.UnlockedPayload,
        poll.LockedPayload,
        poll.ColdNotification,
        poll.WarmNotification,
    )
    lines.extend(_interface(model) for model in models)
    lines += [
        "export type PollChannel = typeof CHANNELS[number];",
        f"export type ClientNotificationState = {_ts_type(poll.ClientNotificationState.__value__)};",
        "interface PollDescriptorFields {",
    ]
    for kind, model in poll.DESCRIPTOR_MODELS.items():
        hints = get_type_hints(model)
        data = " ".join(
            f"{key}: {'PollChannel' if key == 'channel' else _ts_type(hint)};"
            for key, hint in hints.items()
            if key not in ("id", "type")
        )
        lines.append(f"\t{json.dumps(kind)}: {{ {data} }};")
    lines.extend(["}", "interface PollPayloads {"])
    if poll.POLL_PAYLOADS.keys() != poll.POLL_TYPES:
        raise ValueError("Every descriptor must declare its response payload.")
    for kind, annotation in poll.POLL_PAYLOADS.items():
        lines.append(f"\t{json.dumps(kind)}: {_ts_type(annotation)};")
    lines.extend(
        [
            "}",
            "export type PollType = keyof PollDescriptorFields;",
            "export type PollDescriptor<T extends PollType = PollType> = {",
            "\t[K in T]: { id: string; type: K } & PollDescriptorFields[K];",
            "}[T];",
            "export type PollResult<T extends PollType = PollType> = {",
            "\t[K in T]: { id: string; type: K } & (",
        ]
    )
    for status, members in poll.RESULT_MEMBERS.items():
        revision = (
            'revision: NonNullable<PollDescriptorFields[K]["revision"]>'
            if "revision" in members
            else "revision?: never"
        )
        payload = (
            "payload: PollPayloads[K]" if "payload" in members else "payload?: never"
        )
        lines.append(
            f'\t\t| {{ status: "{status}"; {revision}; {payload}; poll_after_ms: number }}'
        )
    lines.extend(["\t);", "}[T];", "export interface PollRequest {"])
    hints = get_type_hints(poll.PollRequest)
    for key in (*poll.REQUEST_FIELDS, *poll.OPTIONAL_REQUEST_FIELDS):
        optional = key in poll.OPTIONAL_REQUEST_FIELDS
        hint = hints[key]
        if optional and type(None) in get_args(hint):
            # The parser supplies None for an absent wire member.
            member = " | ".join(
                _ts_type(arg) for arg in get_args(hint) if arg is not type(None)
            )
        else:
            member = (
                "typeof POLL_PROTOCOL_VERSION" if key == "version" else _ts_type(hint)
            )
        lines.append(f"\t{key}{'?' if optional else ''}: {member};")
    lines.extend(
        [
            "}",
            "export interface PollResponse { version: typeof POLL_PROTOCOL_VERSION; results: PollResult[]; }",
        ]
    )
    return "\n".join(lines) + "\n"


def render_mcp() -> str:
    from lagniappe.core.tools.ai.external.openapi import build_openapi_document

    api = build_openapi_document(
        app_name="Lagniappe", server_url="https://example.test"
    )
    components = cast(dict[str, dict[str, Any]], api["components"])["schemas"]

    def expand(value: Any) -> Any:
        if isinstance(value, list):
            return [expand(child) for child in value]
        if isinstance(value, dict):
            if "$ref" in value:
                name = value["$ref"].removeprefix("#/components/schemas/")
                return expand(components[name])
            return {
                key: {name: expand(schema) for name, schema in child.items()}
                if key == "properties"
                else expand(child)
                for key, child in value.items()
                if key != "description"
            }
        return value

    names = (
        "Actor",
        "AnswerContext",
        "PlanFile",
        "Plan",
        "SubmissionReceipt",
        "PlanContract",
        "PlanSchemaContract",
    )
    schemas = {name: expand(components[name]) for name in names}
    paths = cast(dict[str, dict[str, Any]], api["paths"])
    operations = {op["operationId"]: op for route in paths.values() for op in route.values()}
    for name in ("createPlan", "submitPlan", "executePlan", "createArtifact"):
        schemas[name] = expand(operations[name]["requestBody"]["content"]["application/json"]["schema"])
    return json.dumps(schemas, indent=2) + "\n"


def sync_outputs(root: Path, outputs: Mapping[Path, str], *, check: bool) -> list[Path]:
    stale = []
    for relative, content in outputs.items():
        path = root / relative
        if path.is_file() and path.read_text(encoding="utf-8") == content:
            continue
        stale.append(relative)
        if not check:
            with TemporaryDirectory(dir=path.parent) as directory:
                candidate = Path(directory) / path.name
                candidate.write_text(content, encoding="utf-8", newline="\n")
                candidate.replace(path)
    return stale


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    os.environ.update(
        FLASK_ENV="testing",
        LAGNIAPPE_OFFLINE_WEB_TEST="1",
        LAGNIAPPE_CONFIG_ROOT=str(ROOT / "testing/fixtures/offline-runtime"),
    )
    stale = sync_outputs(
        ROOT, {POLL_OUTPUT: render_poll(), MCP_OUTPUT: render_mcp()}, check=args.check
    )
    if stale and args.check:
        print("Regenerate with venv/bin/python -m runner.wire_contracts:", *stale)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

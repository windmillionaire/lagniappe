"""Regenerate text webfonts from pinned sources without narrowing document coverage.

Install build/font-requirements.txt, then run with the project virtualenv.
Regular Rollup builds need neither these packages nor network access.
"""

import argparse
import hashlib
from io import BytesIO
import json
from pathlib import Path
import subprocess
import unicodedata

from fontTools import subset
from fontTools.ttLib import TTFont


ROOT = Path(__file__).resolve().parents[1]
FONTS = ROOT / "src/fonts"
# A loading boundary, not a content allowlist: every other codepoint goes into
# the extended face. Include combining accents for decomposed Latin text and
# the font's directional arrows so ordinary UI text never needs a fallback.
COMMON = (
    set(range(0x100))
    | set(range(0x300, 0x370))
    | set(range(0x2000, 0x2070))
    | set(range(0x2190, 0x21A0))
    | {
        0x131, 0x152, 0x153, 0x2BB, 0x2BC, 0x2C6, 0x2DA, 0x2DC,
        0x2074, 0x20AC, 0x2122, 0x2212, 0x2215, 0xFEFF, 0xFFFD,
    }
)


def unicode_ranges(codepoints):
    """Describe actual character coverage, including supplementary planes."""
    spans = []
    for value in sorted(codepoints):
        if spans and value == spans[-1][1] + 1:
            spans[-1][1] = value
        else:
            spans.append([value, value])
    return ", ".join(
        f"U+{start:04X}" + (f"-{end:04X}" if end != start else "")
        for start, end in spans
    )


def generate():
    """Return deterministic fonts and CSS after checking complete cmap coverage."""
    outputs = {}
    css = [
        '/* Generated by build/subset_fonts.py; edit its inputs, not this file. */',
        '@import "./icons.css";',
        '',
        '@font-face {',
        '\tfont-family: "Material Symbols Rounded";',
        '\tfont-style: normal;',
        '\tfont-weight: 300 600;',
        '\tfont-display: block;',
        '\tsrc: url("/fonts/material-symbols-rounded.woff2") format("woff2");',
        '}',
    ]
    for record in json.loads((FONTS / "sources.json").read_text())["fonts"]:
        source = (FONTS / record["source"]).read_bytes()
        if hashlib.sha256(source).hexdigest() != record["sha256"]:
            raise ValueError(f"Upstream font digest mismatch: {record['source']}")
        original = TTFont(BytesIO(source), recalcTimestamp=False)
        coverage = set(original.getBestCmap())
        # Marks must remain with their bases in either face so decomposed
        # accents still shape correctly in Latin, Greek and Cyrillic text.
        marks = {cp for cp in coverage if unicodedata.category(chr(cp)).startswith("M")}
        partitions = (
            [("extended", (coverage - COMMON) | marks), ("latin", coverage & COMMON)]
            if record["partition"] else [(None, coverage)]
        )
        retained = set()
        for label, codepoints in partitions:
            font = TTFont(BytesIO(source), recalcTimestamp=False)
            if record["partition"]:
                options = subset.Options()
                options.layout_features = ["*"]
                options.name_IDs += [13, 14]
                options.recalc_timestamp = False
                subsetter = subset.Subsetter(options=options)
                subsetter.populate(unicodes=codepoints)
                subsetter.subset(font)
                font.flavor = "woff2"
                buffer = BytesIO()
                font.save(buffer)
                payload = buffer.getvalue()
            else:
                payload = source
            actual = set(TTFont(BytesIO(payload)).getBestCmap())
            if actual != codepoints:
                raise ValueError(f"Subset coverage mismatch: {record['name']} {label}")
            if label == "latin" and not set(map(ord, "←↑→↓")).issubset(actual):
                raise ValueError(f"Missing primary arrows: {record['name']}")
            retained.update(actual)
            name = record["name"] + (f"-{label}" if label else "")
            outputs[FONTS / f"{name}.woff2"] = payload
            css.extend([
                '',
                f'/* {record["family"]}: {label or name.rsplit("-", 1)[-1]} */',
                '@font-face {',
                f'\tfont-family: "{record["family"]}";',
                f'\tfont-style: {record["style"]};',
                f'\tfont-weight: {record["weight"]};',
                '\tfont-display: swap;',
                f'\tsrc: url("/fonts/{name}.woff2") format("woff2");',
                '\tunicode-range:',
                f'\t\t{unicode_ranges(actual)};',
                '}',
            ])
            print(f"{name}: {len(payload):,} bytes; {len(actual):,} codepoints")
        if retained != coverage:
            raise ValueError(f"Lost document characters: {record['name']}")
    formatted = subprocess.run(
        [str(ROOT / "node_modules/.bin/biome"), "format", "--stdin-file-path=src/style/fonts.css"],
        input=("\n".join(css) + "\n").encode(),
        capture_output=True,
        check=True,
        cwd=ROOT,
    )
    outputs[ROOT / "src/style/fonts.css"] = formatted.stdout
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify committed outputs")
    args = parser.parse_args()
    for path, payload in generate().items():
        if args.check:
            if not path.exists() or path.read_bytes() != payload:
                raise SystemExit(f"Regenerate stale font output: {path.relative_to(ROOT)}")
        else:
            path.write_bytes(payload)


if __name__ == "__main__":
    main()

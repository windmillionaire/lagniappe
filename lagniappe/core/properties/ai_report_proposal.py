"""Stored AI report proposal and identity helpers."""

from __future__ import annotations

from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from lagniappe.core.tools.ai.reporting.contracts.actions import ReportProposal
    from lagniappe.core.tools.files.html import SafeHTML


import hashlib
import json
from collections import Counter

from ..report_contracts import MAX_PROPOSAL_ACTIONS
from ..tools.files.html import sanitize_html
from .ai_report_process import ReportProcessValue


def proposal_fingerprint(proposal: object) -> str:
    canonical = json.dumps(
        proposal,
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=False,
    )
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


class Proposal(ReportProcessValue["ReportProposal"]):
    """Structured action proposal generated by AI."""

    _id = "proposal"

    @property
    def action_summary(self) -> dict[str, object]:
        maximum = None
        if self.entity.origin == "api":
            maximum = MAX_PROPOSAL_ACTIONS
        return summarize_actions(self.value, maximum=maximum)

    @property
    def display_actions(self) -> list[dict[str, object]]:
        from ..tools.ai.reporting.display import proposal_display_actions

        return proposal_display_actions(self)

    @property
    def answer_html(self) -> SafeHTML | None:
        if not isinstance(self.value, dict):
            return None

        answer = self.value.get("answer_html")
        if not answer:
            return None

        return sanitize_html(answer)


def summarize_actions(proposal: ReportProposal | None, *, maximum: int | None = None) -> dict[str, object]:
    actions = (proposal or {}).get("actions", [])
    counts = Counter(action["type"] for action in actions)
    result = {"total": len(actions), "by_type": dict(sorted(counts.items()))}
    if maximum is not None:
        result["maximum"] = maximum
    return result
